// Generates src/wowlua/generated/{apinames,enum}.lua from Ketho's vscode-wow-api
// annotations (MIT, https://github.com/Ketho/vscode-wow-api), which mirror Blizzard's
// own API documentation.
//
//   node tools/gen-wowapi.mjs <path to vscode-wow-api/Annotations/Core>
//
// apinames.lua: names of real C-API functions (global + C_* namespaces) and widget
//   methods per widget type. The emulator uses them to tell "real WoW API, not emulated
//   yet" (logged no-op stub) from "doesn't exist in WoW" (nil, errors like in-game).
// enum.lua: the real Enum.* and Constants.* tables.
import fs from "fs";
import path from "path";

const core = process.argv[2];
if (!core || !fs.existsSync(path.join(core, "Widget"))) {
  console.error("usage: node tools/gen-wowapi.mjs <vscode-wow-api/Annotations/Core>");
  process.exit(1);
}
const outDir = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..", "src", "wowlua", "generated");
fs.mkdirSync(outDir, { recursive: true });

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(path.join(dir, d.name)) : d.name.endsWith(".lua") ? [path.join(dir, d.name)] : []);
}

// ---- widgets ----
const widgets = {}; // name -> { parents: [], methods: Set }
for (const file of walk(path.join(core, "Widget"))) {
  const src = fs.readFileSync(file, "utf8");
  for (const m of src.matchAll(/^---@class (\w+)(?: : ([\w, ]+))?/gm)) {
    const name = m[1];
    if (name !== name[0].toUpperCase() + name.slice(1) || /^[A-Z]+$/.test(name)) continue; // skip lower/UPPER aliases
    widgets[name] ??= { parents: [], methods: new Set() };
    if (m[2]) widgets[name].parents = m[2].split(",").map((s) => s.trim());
  }
  for (const m of src.matchAll(/^function (\w+):(\w+)\(/gm)) {
    (widgets[m[1]] ??= { parents: [], methods: new Set() }).methods.add(m[2]);
  }
}

// ---- C API functions ----
const globals = new Set();
const namespaces = {};
for (const file of walk(path.join(core, "Blizzard_APIDocumentationGenerated"))) {
  const src = fs.readFileSync(file, "utf8");
  for (const m of src.matchAll(/^function (\w+)\(/gm)) globals.add(m[1]);
  for (const m of src.matchAll(/^function (C_\w+)\.(\w+)\(/gm)) (namespaces[m[1]] ??= new Set()).add(m[2]);
}

const q = (s) => JSON.stringify(s);
const list = (set) => "{ " + [...set].sort().map(q).join(", ") + " }";
let out = "-- GENERATED by tools/gen-wowapi.mjs from Ketho/vscode-wow-api annotations (MIT). Do not edit.\n";
out += "return {\n  widgets = {\n";
for (const name of Object.keys(widgets).sort()) {
  const w = widgets[name];
  out += `    ${name} = { parents = ${list(w.parents)}, methods = ${list(w.methods)} },\n`;
}
out += "  },\n  globals = " + list(globals) + ",\n  namespaces = {\n";
for (const ns of Object.keys(namespaces).sort()) out += `    ${ns} = ${list(namespaces[ns])},\n`;
out += "  },\n}\n";
fs.writeFileSync(path.join(outDir, "apinames.lua"), out);

// ---- Enum / Constants ----
const enumSrc = fs.readFileSync(path.join(core, "Data", "Enum.lua"), "utf8")
  .split(/\r?\n/).filter((l) => !/^\s*---/.test(l)).join("\n");
fs.writeFileSync(path.join(outDir, "enum.lua"),
  "-- GENERATED by tools/gen-wowapi.mjs from Ketho/vscode-wow-api annotations (MIT). Do not edit.\n" + enumSrc);

console.log(`widgets: ${Object.keys(widgets).length}, globals: ${globals.size}, namespaces: ${Object.keys(namespaces).length}`);
